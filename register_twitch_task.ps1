<#
register_twitch_task.ps1 - runs twitch_recorder.py every 10 minutes, hidden, forever.

Each run takes a few seconds and appends one snapshot to output\twitch_log\YYYY-MM.csv.
Edit twitch_watch.txt anytime to change which channels and games are tracked.

Run once (no admin needed):
    powershell -ExecutionPolicy Bypass -File register_twitch_task.ps1
Remove it:
    Unregister-ScheduledTask -TaskName "FSR Twitch Recorder" -Confirm:$false
#>

$ErrorActionPreference = "Stop"
$TaskName = "FSR Twitch Recorder"
$Repo     = $PSScriptRoot
$Python   = Join-Path $Repo ".venv\Scripts\python.exe"
$Script   = Join-Path $Repo "twitch_recorder.py"
$Log      = Join-Path $Repo "output\twitch_log\last_run.log"
New-Item -ItemType Directory -Force (Split-Path $Log) | Out-Null

$Cmd = "cmd.exe /c set PYTHONIOENCODING=utf-8&& `"$Python`" `"$Script`" > `"$Log`" 2>&1"
$Vbs = Join-Path $Repo "scripts\run_twitch_hidden.vbs"
New-Item -ItemType Directory -Force (Split-Path $Vbs) | Out-Null
Set-Content -Path $Vbs -Encoding ASCII -Value @(
    "' generated by register_twitch_task.ps1 - runs the Twitch recorder with no window",
    ('CreateObject("WScript.Shell").Run "' + $Cmd.Replace('"', '""') + '", 0, True')
)

$action   = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$Vbs`"" -WorkingDirectory $Repo
$trigger  = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 10)
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 5) -RunOnlyIfNetworkAvailable -MultipleInstances IgnoreNew

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
    -Description "Snapshots Twitch viewership every 10 minutes for FSR (twitch_recorder.py)." -Force | Out-Null
Write-Output "Registered '$TaskName': every 10 minutes. Log: $Log"
